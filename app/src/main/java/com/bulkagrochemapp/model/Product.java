package com.bulkagrochemapp.model;

public class Product {

    private int id;
    private String name;
    private String image;
    private double price;

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getImage() {
        return image;
    }

    public double getPrice() {
        return price;
    }
}
